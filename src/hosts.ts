export type HostName = 'claude' | 'codex' | 'cursor' | 'gemini' | 'copilot' | 'qwen' | 'goose' | 'droid' | 'devin' | 'augment' | 'opencode' | 'junie';

export const HOST_NAMES: HostName[] = ['claude', 'codex', 'cursor', 'gemini', 'copilot', 'qwen', 'goose', 'droid', 'devin', 'augment', 'opencode', 'junie'];

export type HookScope = 'project' | 'user';

/** Normalised view of a Stop-style hook payload. */
export interface HookInput {
  sessionId: string | null;
  /** Host's turn/prompt id when it provides one (diagnostics only; semantics differ per host). */
  turnId: string | null;
  /** Directory the host reports; may be a subdirectory of the repo. */
  cwd: string | null;
  /** The agent's final message for this turn, when the host provides it. */
  lastMessage: string | null;
  /**
   * True when the host is already continuing because a stop hook blocked. Null when the host has no such flag at all
   * (Goose, Augment, Continue); hook.ts then treats a stop that follows its own block as the continuation.
   */
  stopHookActive: boolean | null;
  /** Cursor: how many automatic follow-ups this conversation has had (any hook). */
  loopCount: number | null;
  /** Cursor / Augment: completed | aborted | error | ... */
  status: string | null;
  /** Claude Code: number of background tasks still running. */
  backgroundTasks: number;
  /** Claude Code / Codex permission mode (plan mode cannot edit files). */
  permissionMode: string | null;
  hookEventName: string | null;
}

/** Normalised view of a post-edit hook payload. */
export interface EditInput {
  /** Files the tool touched (absolute or relative to cwd). */
  files: string[];
  cwd: string | null;
  toolName: string | null;
}

/** Warn-only hook after the agent edits a file. Null when the host has no channel the agent can see. */
export interface EditSupport {
  event: string;
  matcher: string;
  register(settings: Record<string, unknown>, command: string, timeoutSeconds: number, scope?: HookScope): boolean;
  registered(settings: Record<string, unknown>, scope?: HookScope): string | null;
  unregister(settings: Record<string, unknown>, scope?: HookScope): boolean;
  parse(raw: Record<string, unknown>): EditInput;
  /** stdout that adds `text` to the agent's context without blocking. */
  warn(text: string): string;
  /** stdout that says nothing. */
  silent(): string;
  synthetic(root: string, file: string): Record<string, unknown>;
}

/** For `kind: 'file'` hosts the whole settings file is ours (a plugin shim) and is rendered, not merged. */
export interface FileSupport {
  render(stopCommand: string, editCommand: string | null, timeoutSeconds: number, editTimeoutSeconds: number): string;
  /** Null when the text was not generated by isitdone (the file then belongs to the user and is left alone). */
  parse(text: string): { stopCommand: string | null; editCommand: string | null; timeoutSeconds: number | null } | null;
}

export interface HostAdapter {
  name: HostName;
  displayName: string;
  /** 'json': hooks are merged into a JSON settings file. 'file': the file at settingsPath is entirely ours (see `file`). */
  kind: 'json' | 'file';
  file?: FileSupport;
  /** Hook event name as the host spells it. */
  event: string;
  /** Path to the settings file that holds hooks (project-level or user-level). */
  settingsPath(root: string, scope: HookScope): string;
  /** Directories whose presence means this host is used here (project: under root; user: under HOME or its config dir). */
  detect(root: string, scope: HookScope): string[];
  /** Scopes the host reads hooks from. Default: both. */
  scopes?: HookScope[];
  /** Another host whose registration this host also loads (so a second one would run the checks twice). */
  coveredBy?: HostName;
  /** The settings file stores hook timeouts in milliseconds. */
  msTimeouts?: boolean;
  /** Normalise the raw payload. */
  parse(raw: Record<string, unknown>): HookInput;
  /** stdout text that lets the agent stop. */
  allow(systemMessage?: string): string;
  /** stdout text that blocks the stop and feeds `reason` back to the agent. */
  block(reason: string): string;
  /** Add the hook to a settings object (idempotent). Returns true if changed. `scope` matters only where the file shape depends on it. */
  register(settings: Record<string, unknown>, command: string, timeoutSeconds: number, scope?: HookScope): boolean;
  /** Is an isitdone hook already present? */
  registered(settings: Record<string, unknown>, scope?: HookScope): string | null;
  /** Remove any isitdone hook. Returns true if changed. */
  unregister(settings: Record<string, unknown>, scope?: HookScope): boolean;
  /** What the user must do after registration, if anything. */
  postInstallNote: string | null;
  /** Build a realistic synthetic payload for doctor. */
  synthetic(root: string, message: string): Record<string, unknown>;
  edit: EditSupport | null;
}

/** Recognise our own hook command whether it is `npx isitdone hook`, `node .../isitdone.js hook`, or a custom wrapper. */
export const HOOK_MARKER = /\bisitdone\b[^\n]*\bhook\b/;

export function isOurCommand(v: unknown): v is string {
  return typeof v === 'string' && HOOK_MARKER.test(v);
}

/** Is this one of our commands for the edit event (vs the stop event)? */
export function isEditCommand(v: unknown): boolean {
  return isOurCommand(v) && /--event[=\s]+edit\b/.test(v);
}

function str(v: unknown): string | null {
  return typeof v === 'string' && v !== '' ? v : null;
}
function num(v: unknown): number | null {
  return typeof v === 'number' && Number.isFinite(v) ? v : null;
}
function arr(v: unknown): unknown[] {
  return Array.isArray(v) ? v : [];
}
function obj(v: unknown): Record<string, unknown> | null {
  return v !== null && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, unknown>) : null;
}
/** A host flag that may be absent: absent means "the host has no such flag", not false. */
function flag(v: unknown): boolean | null {
  return typeof v === 'boolean' ? v : null;
}

/** `$XDG_CONFIG_HOME` or `~/.config` (OpenCode and Devin use it on every platform, Windows included). */
function xdgConfig(): string {
  return str(process.env.XDG_CONFIG_HOME) ?? join(homedir(), '.config');
}
/** Devin's user config lives in %APPDATA% on Windows and in the XDG config dir elsewhere. */
function devinConfigDir(): string {
  return process.platform === 'win32' ? join(str(process.env.APPDATA) ?? join(homedir(), 'AppData', 'Roaming'), 'devin') : join(xdgConfig(), 'devin');
}

/** Pick the workspace root that contains the process cwd (Cursor runs project hooks from the project root). */
function pickRoot(roots: unknown[]): string | null {
  const list = roots.filter((r): r is string => typeof r === 'string' && r !== '');
  if (list.length === 0) return null;
  if (list.length === 1) return list[0] as string;
  const cwd = resolve(process.cwd()).toLowerCase();
  const inside = list.find((r) => {
    const rr = resolve(r).toLowerCase();
    return cwd === rr || cwd.startsWith(rr.endsWith('\\') || rr.endsWith('/') ? rr : rr + (process.platform === 'win32' ? '\\' : '/'));
  });
  return inside ?? (list[0] as string);
}

/** Files named in a Codex / OpenCode apply_patch document. */
export function patchPaths(patch: string): string[] {
  const out: string[] = [];
  for (const m of patch.matchAll(/^\s*\*\*\* (Update File|Add File|Delete File|Move to): (.+?)\s*$/gm)) {
    // "*** Update File: X" followed by "*** Move to: Y" is one change; the agent now owns Y.
    if (m[1] === 'Move to' && out.length > 0) out.pop();
    out.push(m[2] as string);
  }
  return [...new Set(out)];
}

interface ClaudeStyleOpts {
  matcher?: string;
  /** Extra keys on the hook entry (Gemini/Qwen `name`). */
  extra?: Record<string, unknown>;
  /** Extra keys on the group (Augment `metadata`). */
  groupExtra?: Record<string, unknown>;
  /** The settings object itself is the event map (Droid hooks.json, Devin hooks.v1.json) instead of `settings.hooks`. */
  unwrapped?: boolean;
  isMine: (v: unknown) => boolean;
}

/** The object that maps event names to hook groups. */
function hooksMap(settings: Record<string, unknown>, unwrapped: boolean | undefined, create: boolean): Record<string, unknown> | null {
  if (unwrapped) return settings;
  const existing = obj(settings.hooks);
  if (existing) return existing;
  return create ? (settings.hooks = {}) : null;
}

/** Does `have` already carry everything in `want`? Objects are compared key by key so user-added keys do not count as drift. */
function carries(have: unknown, want: unknown): boolean {
  const ho = obj(have);
  const wo = obj(want);
  if (ho && wo) return Object.entries(wo).every(([k, v]) => carries(ho[k], v));
  return JSON.stringify(have) === JSON.stringify(want);
}

/** Claude Code / Codex / Gemini and most newer hosts share the `hooks.<Event>[].hooks[]` shape. */
function registerClaudeStyle(settings: Record<string, unknown>, event: string, command: string, timeout: number, opts: ClaudeStyleOpts): boolean {
  const hooks = hooksMap(settings, opts.unwrapped, true) as Record<string, unknown>;
  const groups = (hooks[event] = arr(hooks[event]));
  const groupExtra = opts.groupExtra ?? {};
  for (const g of groups) {
    const go = obj(g);
    if (!go) continue;
    for (const h of arr(go.hooks)) {
      const ho = obj(h);
      if (ho && opts.isMine(ho.command)) {
        const sameGroup = (opts.matcher === undefined || go.matcher === opts.matcher) && Object.entries(groupExtra).every(([k, v]) => carries(go[k], v));
        if (ho.command === command && ho.timeout === timeout && sameGroup) return false;
        ho.command = command;
        ho.timeout = timeout;
        if (opts.matcher !== undefined) go.matcher = opts.matcher;
        for (const [k, v] of Object.entries(groupExtra)) {
          const existing = obj(go[k]);
          go[k] = existing && obj(v) ? { ...existing, ...(v as Record<string, unknown>) } : v;
        }
        return true;
      }
    }
  }
  groups.push({ ...(opts.matcher !== undefined ? { matcher: opts.matcher } : {}), ...groupExtra, hooks: [{ type: 'command', command, timeout, ...(opts.extra ?? {}) }] });
  return true;
}

function registeredClaudeStyle(settings: Record<string, unknown>, event: string, isMine: (v: unknown) => boolean, unwrapped?: boolean): string | null {
  for (const g of arr(hooksMap(settings, unwrapped, false)?.[event])) {
    for (const h of arr(obj(g)?.hooks)) {
      const cmd = obj(h)?.command;
      if (isMine(cmd)) return cmd as string;
    }
  }
  return null;
}

function unregisterClaudeStyle(settings: Record<string, unknown>, event: string, isMine: (v: unknown) => boolean, unwrapped?: boolean): boolean {
  const hooks = hooksMap(settings, unwrapped, false);
  if (!hooks) return false;
  const groups = arr(hooks[event]);
  let changed = false;
  const kept = groups.filter((g) => {
    const go = obj(g);
    if (!go) return true;
    const before = arr(go.hooks).length;
    go.hooks = arr(go.hooks).filter((h) => !isMine(obj(h)?.command));
    if ((go.hooks as unknown[]).length !== before) changed = true;
    return (go.hooks as unknown[]).length > 0;
  });
  if (kept.length !== groups.length) changed = true;
  if (kept.length === 0) delete hooks[event];
  else hooks[event] = kept;
  if (!unwrapped && Object.keys(hooks).length === 0) delete settings.hooks;
  return changed;
}

const isStop = (v: unknown) => isOurCommand(v) && !isEditCommand(v);

function additionalContext(eventName: string, text: string): string {
  return JSON.stringify({ hookSpecificOutput: { hookEventName: eventName, additionalContext: text } });
}

function editFiles(raw: Record<string, unknown>): string[] {
  const input = obj(raw.tool_input) ?? {};
  const files: string[] = [];
  // file_path: Claude Code, Codex, Gemini, Devin; filePath: OpenCode.
  for (const k of ['file_path', 'filePath', 'notebook_path', 'path']) {
    const v = str(input[k]);
    if (v) files.push(v);
  }
  if (typeof input.command === 'string' && /\*\*\* (?:Begin Patch|Update File|Add File)/.test(input.command)) files.push(...patchPaths(input.command));
  if (typeof input.patchText === 'string') files.push(...patchPaths(input.patchText));
  for (const e of arr(input.edits)) {
    const p = str(obj(e)?.file_path);
    if (p) files.push(p);
  }
  return [...new Set(files)];
}

/** A Claude-shaped Stop payload (Claude Code, Qwen Code, Droid, Devin, Junie share the field names). */
function parseClaudeShape(raw: Record<string, unknown>): HookInput {
  return {
    sessionId: str(raw.session_id),
    turnId: str(raw.prompt_id),
    cwd: str(raw.cwd),
    lastMessage: str(raw.last_assistant_message),
    stopHookActive: raw.stop_hook_active === true,
    loopCount: null,
    status: null,
    backgroundTasks: arr(raw.background_tasks).length,
    permissionMode: str(raw.permission_mode),
    hookEventName: str(raw.hook_event_name),
  };
}

