export const HOSTS: Record<HostName, HostAdapter> = { claude, codex, cursor, gemini, copilot, qwen, goose, droid, devin, augment, opencode, junie };

export function getHost(name: string): HostAdapter {
  const h = (HOSTS as Record<string, HostAdapter>)[name];
  if (!h) throw new Error(`unknown host "${name}" (expected one of ${HOST_NAMES.join(', ')})`);
  return h;
}

export function hostScopes(host: HostAdapter): HookScope[] {
  return host.scopes ?? ['project', 'user'];
}

/** Hosts whose settings dir exists in this repo (project) or the home directory (user), in a stable order. */
export function detectHosts(root: string, exists: (p: string) => boolean): Array<{ host: HostAdapter; scope: HookScope; path: string }> {
  const found: Array<{ host: HostAdapter; scope: HookScope; path: string }> = [];
  for (const name of HOST_NAMES) {
    const host = HOSTS[name];
    for (const scope of hostScopes(host)) {
      if (host.detect(root, scope).some(exists)) found.push({ host, scope, path: host.settingsPath(root, scope) });
    }
  }
  return found;
}
